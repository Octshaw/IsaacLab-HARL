def _array(values, shape):
    result = np.asarray(values, dtype=np.float64)
    if result.shape != shape or not np.isfinite(result).all():
        raise ValueError(f"Expected finite array of shape {shape}, got {result.shape}")
    return result


def inertia_matrix(six):
    """Convert URDF Ixx,Ixy,Ixz,Iyy,Iyz,Izz to a symmetric float64 matrix."""
    xx, xy, xz, yy, yz, zz = _array(six, (6,))
    return np.array(((xx, xy, xz), (xy, yy, yz), (xz, yz, zz)), dtype=np.float64)


def _properties(mass, com, inertia):
    matrix = _array(inertia, (3, 3)).tolist()
    return {"mass": float(mass), "com": _array(com, (3,)).tolist(),
            "inertia3x3": matrix, "inertia": copy.deepcopy(matrix)}


