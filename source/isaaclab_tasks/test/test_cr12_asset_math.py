    def test_recording_error_and_late_failure_preserve_failure(self):
        trace = self.trace()
        self.sample(trace, 0)
        trace.flush()
        before = trace.path.read_bytes()
        trace.mark_failure("render", "failure after stage flush", step=0)
        self.assertEqual(trace.path.read_bytes(), before)
        self.assertTrue(trace.summary()["failures"][-1]["row_already_written"])
        self.sample(trace, 1)
        with mock.patch.object(trace, "_writer") as writer:
            writer.writerow.side_effect = OSError("disk full")
            with self.assertRaisesRegex(OSError, "disk full"):
                trace.flush()
        result = trace.summary()
        self.assertTrue(result["has_failure"])
        self.assertIn("disk full", result["recording_error"])
        trace.close()
        self.assertTrue(trace.summary()["has_failure"])

