    def test_box_and_rotation_parallel_axis_independent_quadrature(self):
        components = [self.real["candidates"][name] for name in ("link_6", "scanner")]
        signs = np.array([[x, y, z] for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)])
        points, weights = [], []
        for body, rotation in zip(components, (np.eye(3), asset.rpy_matrix([0, 0, 3*math.pi/4]))):
            points.extend((np.asarray(body["com"]) + signs*np.asarray(body["size"])/(2*math.sqrt(3))) @ rotation.T)
            weights.extend([body["mass"]/8]*8)
        points, weights = np.array(points), np.array(weights)
        center = (points*weights[:, None]).sum(axis=0)/weights.sum()
        centered = points-center
        covariance = centered.T@(centered*weights[:, None])
        independent = np.trace(covariance)*np.eye(3)-covariance
        np.testing.assert_allclose(independent, self.real["bodies"]["link_6"]["inertia3x3"], atol=1e-14, rtol=0)
        with self.assertRaises(ValueError):
            asset.box_properties(1, [0, 0, 0], [1, 0, 1])

