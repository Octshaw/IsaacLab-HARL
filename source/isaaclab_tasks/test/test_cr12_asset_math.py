    def test_trajectory_segments_endpoints_and_reference_times(self):
        for t, expected in ((0, 0), (1, 0), (2, math.radians(2.5)), (3, math.radians(5)), (6, math.radians(5))):
            q, dq = asset.trajectory(t)
            self.assertAlmostEqual(q[1], expected, places=14)
            np.testing.assert_array_equal(np.delete(q, 1), np.zeros(5))
            if t != 2:
                np.testing.assert_array_equal(dq, np.zeros(6))
        self.assertAlmostEqual(asset.trajectory(2)[1][1], .0818123086872342, places=14)
        h = 1e-5
        finite_difference = (asset.trajectory(1.7+h)[0]-asset.trajectory(1.7-h)[0])/(2*h)
        np.testing.assert_allclose(finite_difference, asset.trajectory(1.7)[1], atol=1e-10, rtol=0)
        self.assertEqual(asset.step_reference_times(119), (119/120, 1))
        self.assertEqual(asset.step_reference_times(719), (719/120, 6))
        self.assertGreater(asset.trajectory(asset.step_reference_times(180)[1])[0][1], asset.trajectory(asset.step_reference_times(180)[0])[0][1])
        for invalid in (-1, 720, 1.5, True):
            with self.assertRaises(ValueError):
                asset.step_reference_times(invalid)
        for invalid in (-.1, 6.1, float("nan")):
            with self.assertRaises(ValueError):
                asset.trajectory(invalid)

